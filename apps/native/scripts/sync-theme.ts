// Turns the web's oklch theme (apps/frontend/src/routes/layout.css) into values React Native can read:
// `global.css` (CSS variables as "R G B" so `bg-primary/10` works) and `theme.generated.json` (hex for
// icons and other places that can't use class names). Run: bun run --filter native sync-theme
import { converter, parse } from 'culori';
import { z } from 'zod';

const source = await Bun.file(
  new URL('../../frontend/src/routes/layout.css', import.meta.url)
).text();
const toRgb = converter('rgb');

const block = (selector: string) =>
  new RegExp(`^${selector.replace('.', '\\.')}\\s*\\{([^}]*)\\}`, 'm').exec(source)?.[1] ?? '';

const tokens = (css: string) =>
  [...css.matchAll(/--([\w-]+):\s*([^;]+);/g)].map(([, name, value]) => ({
    name: z.string().parse(name),
    value: z.string().parse(value).trim(),
  }));

const colorSchema = z.object({
  r: z.number(),
  g: z.number(),
  b: z.number(),
  alpha: z.number().default(1),
});
const channel = (value: number) => Math.round(Math.min(Math.max(value, 0), 1) * 255);

function convert(value: string) {
  const color = colorSchema.safeParse(toRgb(parse(value)));
  if (!color.success) return null; // not a color, e.g. --radius
  const { r, g, b, alpha } = color.data;
  const [R, G, B] = [channel(r), channel(g), channel(b)];
  const hex = `#${[R, G, B].map((c) => c.toString(16).padStart(2, '0')).join('')}`;
  return { channels: `${R} ${G} ${B}`, hex, alpha: Math.round(alpha * 100) / 100 };
}

const light = tokens(block(':root'));
const dark = new Map(tokens(block('.dark')).map((t) => [t.name, t.value]));

const theme: Record<string, { light: string; dark: string; alpha: number }> = {};
const lightVars: string[] = [];
const darkVars: string[] = [];

for (const { name, value } of light) {
  const l = convert(value);
  const d = convert(dark.get(name) ?? value);
  if (!l || !d) continue;
  theme[name] = { light: l.hex, dark: d.hex, alpha: l.alpha };
  lightVars.push(`    --${name}: ${l.channels};`);
  if (dark.has(name)) darkVars.push(`    --${name}: ${d.channels};`);
}

const css = `/* Generated by scripts/sync-theme.ts from apps/frontend/src/routes/layout.css. Do not edit. */
@tailwind base;
@tailwind components;
@tailwind utilities;

@layer base {
  :root {
${lightVars.join('\n')}
  }

  .dark:root {
${darkVars.join('\n')}
  }
}
`;

await Bun.write(new URL('../global.css', import.meta.url), css);
await Bun.write(
  new URL('../theme.generated.json', import.meta.url),
  `${JSON.stringify(theme, null, 2)}\n`
);
console.log(`Wrote ${Object.keys(theme).length} tokens`);
