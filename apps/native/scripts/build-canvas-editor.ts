// Native-only: bundles canvas-editor/ (TipTap + Yjs, which need a DOM) into one HTML page for the canvas WebView,
// written to src/lib/canvas-editor.generated.ts. Run `bun run --filter native build-canvas` after changing it.
import path from 'node:path';

const root = path.join(import.meta.dir, '..');
const result = await Bun.build({
  entrypoints: [path.join(root, 'canvas-editor/index.ts')],
  target: 'browser',
  format: 'iife',
  minify: true,
  define: { 'process.env.NODE_ENV': '"production"' },
});
if (!result.success) {
  console.error(result.logs.join('\n'));
  process.exit(1);
}
const script = (await result.outputs[0]!.text()).replaceAll('</script', '<\\/script');
const style = await Bun.file(path.join(root, 'canvas-editor/style.css')).text();

const html = `<!doctype html>
<html>
<head>
<meta charset="utf-8">
<meta name="viewport" content="width=device-width, initial-scale=1, maximum-scale=1, user-scalable=no">
<style>${style}</style>
</head>
<body>
<div id="editor"></div>
<script>${script}</script>
</body>
</html>`;

await Bun.write(
  path.join(root, 'src/lib/canvas-editor.generated.ts'),
  `// Generated by scripts/build-canvas-editor.ts from canvas-editor/, do not edit.\nexport const canvasEditorHtml = ${JSON.stringify(html)};\n`
);
console.log(`canvas editor: ${Math.round(html.length / 1024)} KiB`);
